"""Write deck/metrics.js from the latest evaluation summary (the same numbers README.md shows, computed the same way),
so the deck never carries hand-typed results. Usage: python deck/build_metrics.py"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPORTS = ROOT / "eval" / "reports"


def main() -> None:
    files = sorted(REPORTS.glob("*-summary.json"))
    if not files:
        sys.exit("no summary yet")
    s = json.loads(files[-1].read_text(encoding="utf-8"))
    det, c = s["content_detection"], s["claim"]
    chans = {k: v for k, v in det["by_channel"].items() if k != "user"}
    docs_n, docs_hit = sum(v["n"] for v in chans.values()), sum(v["detected"] for v in chans.values())
    user = det["by_channel"].get("user") or {}
    fp = s["fpr"]["holdout"] or s["fpr"]["dev"]
    iso = s.get("latency_isolated") or {}
    head = next((e for e in s["e2e"] if e["suite"] == "headline"), s["e2e"][0])
    adaptive = sorted(REPORTS.glob("*-adaptive.json"))
    ad = json.loads(adaptive[-1].read_text(encoding="utf-8")) if adaptive else {}
    m = {
        "date": s["date"], "commit": s["git_sha"],
        "engine": sorted({v for d in s["settings"].get("engine_versions", {}).values() for v in d if v != "None"}),
        "docs_recall": docs_hit / docs_n, "docs_n": docs_n, "channels": len(chans),
        "user_recall": user.get("recall"), "user_n": user.get("n"),
        "fpr": fp["fpr"], "fpr_n": fp["n"], "fpr_dev": (s["fpr"]["dev"] or {}).get("fpr"),
        "p95_ms": iso.get("p95_ms"),
        "utility": (s.get("utility") or {}).get("retention"),
        "cost_ratio": (head.get("overhead") or {}).get("cost_ratio"),
        "token_ratio": (head.get("overhead") or {}).get("token_ratio"),
        "types": [{"type": t["type"], "recall": t["recall"], "n": t["n"]} for t in c["types"]],
        "types_detected": sum(1 for t in c["types"] if (t["recall"] or 0) > 0),
        "e2e": [{"suite": e["suite"], "off": e["off"]["asr"], "on": e["on"]["asr"], "scored_on": e["on"]["scored"],
                 "n_on": e["on"]["n"], "canary_on": e["canary_leaks_on"]} for e in s["e2e"]],
        "e2e_scored_on": sum(e["on"]["scored"] for e in s["e2e"]),
        "e2e_compromised_on": sum(e["on"]["compromised"] for e in s["e2e"]),
        "head_off": head["off"]["asr"], "head_on": head["on"]["asr"],
        "adaptive_scored": sum(r["n"] for r in ad.get("rounds", [])),
        "adaptive_compromised": sum(r["compromised"] for r in ad.get("rounds", [])),
        "by_channel": {k: v.get("recall") for k, v in det["by_channel"].items()},
    }
    latest = lambda kind: (lambda f: json.loads(f[-1].read_text(encoding="utf-8")) if f else {})(sorted(REPORTS.glob(f"*-{kind}.json")))
    ct, pr, rt = latest("contract"), latest("paired"), latest("redteam")
    if ct:   # D-064 intent contract, deterministic, detectors bypassed
        tp, nm = ct["third_party"], ct["named_party"]
        m |= {"ct_actions": tp["actions"], "ct_stopped": tp["contract"]["stopped"],
              "ct_min_rules": min(int(k) for k in tp["independent_rules"]) if tp["independent_rules"] else None,
              "ct_named_n": nm["actions"], "ct_named_contract": nm["contract"]["stopped"],
              "ct_named_previous": nm["intent-terms"]["stopped"],
              "ct_benign_allowed": ct["benign"]["contract"]["allowed"], "ct_benign_n": ct["benign"]["contract"]["actions"]}
    hp = (pr.get("suites") or {}).get("headline") or {}
    if hp.get("arms", {}).get("actions"):   # detectors off on the agent: the action layer alone
        a, pa = hp["arms"]["actions"], hp.get("paired_off_vs_actions") or {}
        m |= {"act_engine": ", ".join(a.get("engines") or []), "act_scored": a["scored"], "act_compromised": a["compromised"], "act_ci_hi": (a["asr_ci95"] or [0, 0])[1],
              "act_hit_off": pa.get("compromised_unprotected"), "act_stopped": (pa.get("prevented_by") or {}).get("stopped-action", 0)}
    if hp.get("paired_off_vs_on"):
        po = hp["paired_off_vs_on"]
        m |= {"pair_n": po["pairs"], "pair_on_ci_hi": (po["asr_protected_ci95"] or [0, 0])[1]}
    rep = pr.get("repeated") or {}
    if rep:
        for arm, v in rep["arms"].items():
            m |= {f"rep_{arm}_n": v["scored"], f"rep_{arm}_c": v["compromised_trials"]}
    if rt:   # D-066 red-team and repair loop
        g = rt["regression"]
        m |= {"rt_failures": rt["failures"], "rt_variants": g["dev_variants"]["caught"], "rt_variants_n": g["dev_variants"]["n"],
              "rt_hold": g["holdout_failures"]["now_caught"], "rt_hold_n": g["holdout_failures"]["n"],
              "rt_fp": g["benign_dev"]["new_false_alarms"] + g["benign_holdout"]["new_false_alarms"],
              "rt_benign_n": g["benign_dev"]["n"] + g["benign_holdout"]["n"], "rt_decision": rt["decision"]}
    out = Path(__file__).with_name("metrics.js")
    out.write_text("// Generated by deck/build_metrics.py from " + files[-1].name + " - do not edit by hand\n"
                   "window.M = " + json.dumps(m, indent=1) + ";\n", encoding="utf-8")
    print("deck metrics from", files[-1].name, "->", out)


if __name__ == "__main__":
    main()
