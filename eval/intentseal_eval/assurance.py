"""Write docs/ASSURANCE.md from the latest contract, paired and red-team reports (never hand-typed numbers):
the intent contract with every detector bypassed (D-064), paired and repeated end-to-end runs with intervals
(D-067), provenance and receipts (D-065), and the red-team and repair loop (D-066).

    python -m intentseal_eval.assurance
"""

from __future__ import annotations

import json
from typing import Any

from .report import REPORTS, ROOT


def latest(kind: str) -> tuple[str | None, dict[str, Any]]:
    f = sorted(REPORTS.glob(f"*-{kind}.json"))
    return (f[-1].name, json.loads(f[-1].read_text(encoding="utf-8"))) if f else (None, {})


def ci(v: list[float] | None) -> str:
    return f"{v[0]:.1%}–{v[1]:.1%}" if v else "—"


def main() -> None:
    (cn, ct), (pn, pr), (rn, rt) = latest("contract"), latest("paired"), latest("redteam")
    out: list[str] = ["# Assurance: what holds when detection fails", "",
                      f"Generated by `python -m intentseal_eval.assurance` from `eval/reports/{cn}`, `{pn}` and `{rn}`. "
                      "Detection results are in [EVALUATION.md](EVALUATION.md); this page asks the harder question: "
                      "if an injection gets past every detector, can the agent still do harm, and can we prove what happened?", ""]
    if ct:
        tp, nm, us = ct["third_party"], ct["named_party"], ct["user_channel"]
        out += ["## 1. Intent contract with every detector bypassed (D-064)", "",
                "**Method.** " + ct["method"], "",
                f"Engine `{ct.get('engine')}` · attack suite {ct['attack_suite']} · {ct['attack_cases']} attack cases demanding at least one action.", "",
                "| Condition | Demanded actions | Intent contract (shipped) | Word-list rule instead | Allow-lists, provenance, scan only |",
                "|---|---|---|---|---|",
                f"| Third-party content (web, files, email, API, ...) | {tp['actions']} | {tp['contract']['stopped']} ({ci(tp['contract']['rate_ci95'])}) | "
                f"{tp['intent-terms']['stopped']} | {tp['bare']['stopped']} |",
                f"| Attacker targets a party the user named, user said \"Do not email them.\" | {nm['actions']} | {nm['contract']['stopped']} "
                f"({ci(nm['contract']['rate_ci95'])}) | {nm['intent-terms']['stopped']} ({ci(nm['intent-terms']['rate_ci95'])}) | {nm['bare']['stopped']} |",
                f"| User channel (the user is the attacker; reported apart) | {us['actions']} | {us['contract']['stopped']} | {us['intent-terms']['stopped']} | {us['bare']['stopped']} |",
                "",
                f"Defence in depth, third-party content: rules that fired per stopped action {tp['independent_rules']}; "
                f"coverage by rule {tp['rule_coverage']}. In the named-party condition provenance cannot fire (the address is in "
                "the user's own words) and internal addresses pass the allow-list: the contract is what stops those sends, "
                "because the previous word-list rule read \"Do not email them\" as a request to email.", "",
                f"Legitimate actions the user asked for (our utility tasks that send or write), contract on: "
                f"{ct['benign']['contract']['allowed']} of {ct['benign']['contract']['actions']} allowed.", ""]
    if pr:
        out += ["## 2. Paired, repeated end-to-end runs on the agent (D-067)", "",
                "**Method.** " + pr["note"], "",
                "| Suite | Arm | Runs | Scored | Compromised | Attack success (95% CI) | Stopped at content | Stopped at action | Resisted | Unscored |",
                "|---|---|---|---|---|---|---|---|---|---|"]
        for suite, s in pr["suites"].items():
            for arm, v in s["arms"].items():
                label = {"off": "unprotected", "on": "protected", "actions": "detectors off"}[arm]
                out.append(f"| `{suite}` | {label} | {v['n']} | {v['scored']} | {v['compromised']} | "
                           f"{(v['asr'] or 0):.1%} ({ci(v['asr_ci95'])}) | {v['stopped-content']} | {v['stopped-action']} | "
                           f"{v['resisted']} | {v['unscored']} |")
        out += ["", "**Paired** (same attack, both runs completed):", "",
                "| Suite | Comparison | Pairs | Compromised unprotected | Prevented (how) | New compromises | Protected attack success (95% CI) |",
                "|---|---|---|---|---|---|---|"]
        for suite, s in pr["suites"].items():
            for k in ("paired_off_vs_on", "paired_off_vs_actions"):
                p = s.get(k)
                if p:
                    out.append(f"| `{suite}` | {'unprotected vs protected' if k.endswith('on') else 'unprotected vs detectors off'} | "
                               f"{p['pairs']} | {p['compromised_unprotected']} | {p['prevented']} {p['prevented_by']} | "
                               f"{p['new_compromise']} | {p['asr_protected']:.1%} ({ci(p['asr_protected_ci95'])}) |")
        out += ["", "\"Resisted\" means no harmful outcome and no recorded intervention: the agent model ignored the attack "
                "that time. A protected run where the model resisted is not counted as the firewall's success; that is why "
                "the attacks that worked are repeated below.", ""]
        rep = pr.get("repeated")
        if rep:
            out += [f"**Repeated trials**: the {rep['attacks']} attacks that compromised the unprotected agent in any "
                    "end-to-end suite, three runs each, every arm on the same agent model chain:", "",
                    "| Arm | Trials | Scored | Compromised trials (95% CI) | Attacks compromised at least once | Outcomes |", "|---|---|---|---|---|---|"]
            for arm, v in rep["arms"].items():
                label = {"off": "unprotected", "on": "protected", "actions": "detectors off"}[arm]
                out.append(f"| {label} | {v['trials']} | {v['scored']} | {v['compromised_trials']} ({ci(v['trial_asr_ci95'])}) | "
                           f"{v['attacks_ever_compromised']} | {v['outcomes']} |")
            out.append("")
    out += ["## 3. Provenance and execution receipts (D-065)", "",
            "Every attempted action is shown as a chain built from the log: the untrusted source (a proven link: the call's "
            "arguments copy that content's text, or its target first appeared there; otherwise earlier flagged content, "
            "marked as context, not proof), the evidence found, the proposed call, the rule and contract clause that "
            "decided, and the outcome. Applications report execution (`POST /v1/actions/{id}/receipt`; automatic in the "
            "SDK's `@guard.tool`), so \"not executed\" rests on the enforced decision plus the application's record, not on "
            "a model's claim. A blocked call reported as run is flagged as a contradiction. Console: Replay → Attack to action. "
            "Tests: `tests/test_contract.py`, `tests/test_gateway.py::test_contract_provenance_and_receipts`.", ""]
    if rt:
        g = rt["regression"]
        out += ["## 4. Red-team and repair loop (D-066)", "",
                f"Suite `{rt['suite']}` run on engine(s) {list(rt['run']['engines'])} ({rt['run']['scored']} scored attacks, "
                f"{rt['failures']} failures). Split {rt['split']['dev']} development / {rt['split']['holdout']} held-out "
                f"({rt['split']['rule']}); {rt['routed_elsewhere']['n']} development failures are not representable as attack "
                f"memory and are routed to detector or policy work.", "",
                "| Largest failure clusters (family · channel · boundary) | Failures |", "|---|---|"]
        out += [f"| {k} | {v} |" for k, v in list(rt["clusters"].items())[:8]]
        out += ["", "| Regression check | Result |", "|---|---|",
                f"| Development variants caught (case, spacing, quoting, code block, benign framing, truncation, reordering) | "
                f"{g['dev_variants']['caught']}/{g['dev_variants']['n']} ({ci(g['dev_variants']['rate_ci95'])}); by mutation {g['dev_variants']['by_mutation']} |",
                f"| Held-out failures now caught (never seen by the repair) | {g['holdout_failures']['now_caught']}/{g['holdout_failures']['n']} "
                f"({ci(g['holdout_failures']['rate_ci95'])}) |",
                f"| New false alarms, development benign set `{g['benign_dev']['set']}` | {g['benign_dev']['new_false_alarms']}/{g['benign_dev']['n']} |",
                f"| New false alarms, held-out benign set `{g['benign_holdout']['set']}` | {g['benign_holdout']['new_false_alarms']}/{g['benign_holdout']['n']} "
                f"({ci(g['benign_holdout']['rate_ci95'])}) |",
                f"| Decision | **{rt['decision']}**: {rt['reason']} |", "", rt["note"], ""]
    out += ["## Reproduce", "", "```bash", "python -m intentseal_eval.contract_eval      # deterministic, no model calls",
            "python -m intentseal_eval.redteam            # deterministic, no model calls",
            "python -m intentseal_eval.paired             # from promptfoo results (sh eval/promptfoo/run_suite.sh headline actions)",
            "python -m intentseal_eval.assurance          # this page", "```", ""]
    path = ROOT / "docs" / "ASSURANCE.md"
    path.write_text("\n".join(out), encoding="utf-8")
    print("wrote", path)


if __name__ == "__main__":
    main()
